# frozen_string_literal: true

require "json"
require "stringio"
require_relative "../test_helper"

class MilkTeaStdCommandTest < Minitest::Test
  def test_std_list_prints_descriptions_and_paths_grouped_by_category
    out = StringIO.new
    err = StringIO.new

    status = MilkTea::CLI.start(["std", "list"], out:, err:)

    assert_equal 0, status
    assert_equal "", err.string

    map_line = out.string.lines.find { |line| line.rstrip.end_with?("#{MilkTea::StdCatalog.std_root}/map.mt") }
    refute_nil(map_line)
    assert_match(/#{Regexp.escape("map")} /, map_line)

    MilkTea::StdCatalog.entries.each do |entry|
      assert_includes(out.string, entry.path)
    end
    refute_includes(out.string, "#{MilkTea::StdCatalog.std_root}/raylib.mt")
  end

  def test_std_list_json_emits_machine_readable_entries
    out = StringIO.new
    err = StringIO.new

    status = MilkTea::CLI.start(["std", "list", "--json"], out:, err:)

    assert_equal 0, status
    entries = JSON.parse(out.string)
    names = entries.map { |entry| entry["name"] }

    assert_includes(names, "map")
    refute_includes(names, "raylib")
    entry = entries.find { |item| item["name"] == "mem.arena" }
    assert_equal("Memory", entry["category"])
    assert(entry["description"].is_a?(String) && !entry["description"].empty?)
    assert(File.file?(entry["path"]))
  end

  def test_std_show_prints_module_source
    out = StringIO.new
    err = StringIO.new

    status = MilkTea::CLI.start(["std", "show", "option"], out:, err:)

    assert_equal 0, status
    assert_equal "", err.string
    assert_equal(File.read(File.join(MilkTea::StdCatalog.std_root, "option.mt")), out.string)
  end

  def test_std_show_resolves_slashed_namespace_names
    out = StringIO.new
    err = StringIO.new

    status = MilkTea::CLI.start(["std", "show", "mem/arena"], out:, err:)

    assert_equal 0, status
    assert_equal(File.read(File.join(MilkTea::StdCatalog.std_root, "mem", "arena.mt")), out.string)
  end

  def test_std_show_resolves_platform_variant_to_host_platform
    out = StringIO.new
    err = StringIO.new
    host = MilkTea.host_platform.to_s

    status = MilkTea::CLI.start(["std", "show", "fs"], out:, err:)

    assert_equal 0, status
    assert_equal(File.read(File.join(MilkTea::StdCatalog.std_root, "fs.#{host}.mt")), out.string)
  end

  def test_std_show_can_print_generated_modules
    out = StringIO.new
    err = StringIO.new

    status = MilkTea::CLI.start(["std", "show", "c.cjson"], out:, err:)

    assert_equal 0, status
    assert(out.string.start_with?("# generated by mtc"))
  end

  def test_std_show_unknown_module_fails
    out = StringIO.new
    err = StringIO.new

    status = MilkTea::CLI.start(["std", "show", "does.not.exist"], out:, err:)

    assert_equal 1, status
    assert_includes(err.string, "std module not found: does.not.exist")
  end

  def test_std_unknown_subcommand_fails
    out = StringIO.new
    err = StringIO.new

    status = MilkTea::CLI.start(["std", "wat"], out:, err:)

    assert_equal 1, status
    assert_includes(err.string, "unknown std subcommand wat")
  end
end
