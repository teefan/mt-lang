#!/usr/bin/env ruby
# frozen_string_literal: true
#
# gen_cli_help — generate the self-host's `cli_help.mt` from the Ruby host's own
# help output, so the two CLIs cannot drift apart by transcription.
#
# The host's help text is its *observable output*, so this captures it by
# running the host CLI in-process rather than parsing its source:
#   * general help   — `mtc` with no arguments (stdout)
#   * usage block    — `mtc <unknown-command>` (stderr)
#   * command help   — `mtc help <command>` (stdout) for every COMMANDS entry
#
# Usage:
#   ruby tools/gen_cli_help.rb [--check]
#
#   --check   exit 1 when the checked-in file differs (for CI / the parity gate)

ROOT = File.expand_path("..", __dir__)
$LOAD_PATH.unshift(File.join(ROOT, "lib"))

require "stringio"
require "milk_tea"

OUT_PATH = File.join(ROOT, "projects", "mtc", "src", "mtc", "cli_help.mt")

def capture(argv)
  out = StringIO.new
  err = StringIO.new
  rc = MilkTea::CLI.start(argv.dup, out: out, err: err)
  [out.string, err.string, rc]
end

def lines_of(text)
  list = text.split("\n", -1)
  list.pop if list.last == ""
  list
end

def mt_string(text)
  %("#{text.gsub('\\', '\\\\\\\\').gsub('"', '\\"')}")
end

help_text, = capture([])
_, usage_text, = capture(["__mtc_unknown_command__"])
raise "host printed no help text" if help_text.empty?
raise "host printed no usage text" if usage_text.empty?

commands = MilkTea::CLI::COMMANDS.map { |name, _| name }
blocks = commands.to_h { |name| [name, capture(["help", name]).first] }
raise "host printed no help for a command" if blocks.values.any?(&:empty?)

# One helper per command family keeps `print_command_help` a small dispatcher
# while the help lines stay inline in declaration order (no constant tables).
HELP_GROUPS = [
  { id: "cli", commands: %w[check build run run-module] },
  { id: "project", commands: %w[test new format] },
  { id: "source", commands: %w[lint lex parse lower emit-c debug] },
  { id: "tooling", commands: %w[deps toolchain bindgen cache] },
  { id: "server", commands: %w[docs std snapshot lsp dap completions] },
].freeze
grouped = HELP_GROUPS.flat_map { |group| group[:commands] }
raise "help groups do not match COMMANDS: #{commands.inspect}" unless grouped == commands

buf = +""
buf << "# Generated by tools/gen_cli_help.rb — do not edit by hand.\n"
buf << "#\n"
buf << "# The strings below are the Ruby host's own help output, captured in-process:\n"
buf << "#   mtc (no args)        -> general help\n"
buf << "#   mtc <unknown>        -> usage block\n"
buf << "#   mtc help <command>   -> per-command help\n"
buf << "# Must always match host milk_tea #{MilkTea::VERSION}.\n"
buf << "# Regenerate with: ruby tools/gen_cli_help.rb\n\n"
buf << "import std.stdio as stdio\n"
buf << "import std.terminal as terminal\n\n\n"
buf << "## The CLI version string, printed by `mtc version` exactly as the host prints\n"
buf << "## `MilkTea::VERSION`; regenerated with the help text so the two cannot drift.\n"
buf << "public const VERSION: str = #{mt_string(MilkTea::VERSION)}\n\n\n"
buf << "## Emit one line of a help block to stdout, or to stderr when `to_err`.\n"
buf << "function emit_line(to_err: bool, text: str) -> void:\n"
buf << "    if to_err:\n"
buf << "        let _ = terminal.write_stderr(text)\n"
buf << "        let _ = terminal.write_stderr(\"\\n\")\n"
buf << "    else:\n"
buf << "        stdio.print_line(text)\n\n\n"

def emit_block(buf, signature, lines)
  buf << "#{signature}:\n"
  lines.each { |l| buf << "    emit_line(to_err, #{mt_string(l)})\n" }
  buf << "    if to_err:\n"
  buf << "        let _ = terminal.flush_stderr()\n"
end

emit_block(buf, "## The host's general help (`mtc`, `mtc help`, `mtc --help`).\npublic function print_help(to_err: bool) -> void", lines_of(help_text))
buf << "\n\n"
emit_block(buf, "## The host's usage block (unknown command, unsupported option).\npublic function print_usage(to_err: bool) -> void", lines_of(usage_text))

buf << "\n\n"
HELP_GROUPS.each do |group|
  buf << "## Per-command help for the #{group[:id]} command family.\n"
  buf << "function print_#{group[:id]}_command_help(command: str, to_err: bool) -> bool:\n"
  group[:commands].each do |name|
    buf << "    if command == #{mt_string(name)}:\n"
    lines_of(blocks[name]).each { |l| buf << "        emit_line(to_err, #{mt_string(l)})\n" }
    buf << "        if to_err:\n"
    buf << "            let _ = terminal.flush_stderr()\n"
    buf << "        return true\n"
  end
  buf << "    return false\n\n\n"
end

buf << "## The host's per-command help (`mtc help <command>`, `mtc <command> --help`).\n"
buf << "## Returns false when the command has no help block, like the host's fallback.\n"
buf << "public function print_command_help(command: str, to_err: bool) -> bool:\n"
HELP_GROUPS.each do |group|
  buf << "    if print_#{group[:id]}_command_help(command, to_err):\n"
  buf << "        return true\n"
end
buf << "    return false\n"

if ARGV.include?("--check")
  if File.exist?(OUT_PATH) && File.read(OUT_PATH) == buf
    puts "cli_help.mt is up to date (#{commands.length} commands, #{lines_of(help_text).length} help lines)"
    exit 0
  end
  warn "cli_help.mt is out of date — run: ruby tools/gen_cli_help.rb"
  exit 1
end

File.write(OUT_PATH, buf)
puts "wrote #{OUT_PATH.sub(ROOT + '/', '')} " \
     "(#{commands.length} commands, help #{lines_of(help_text).length} lines, usage #{lines_of(usage_text).length} lines)"
