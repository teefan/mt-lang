    def self.start(argv = ARGV, out: $stdout, err: $stderr, source_overrides: nil, build_frontend: nil)
      new(argv, out:, err:, source_overrides:, build_frontend:).start
    end

    def initialize(argv, out:, err:, source_overrides: nil, build_frontend: nil)
      @argv = argv.dup
      @out = out
      @err = err
      @include_module_roots = []
      @include_path_flags = []
      @ambient_module_roots = MilkTea::ModuleRoots.roots_for_path(Dir.pwd)
      @source_overrides = normalize_source_overrides(source_overrides)
      @build_frontend = build_frontend
      @color = :auto
      @verbose = false
      @quiet = false
    end

    def start
      return 1 unless extract_global_options!

      extract_include_paths!
      command = @argv.shift

      if version_request?(command)
        @out.puts("mtc #{MilkTea::VERSION}")
        return 0
      end

      if help_request?(command)
        topic = command == "help" ? @argv.shift : nil
        if topic
          print_command_help(topic, @out)
        else
          print_help(@out)
        end
        return 0
      end

      if command && @include_module_roots.any? && !command_supports_include_paths?(command)
        @err.puts("unknown option #{@include_path_flags.first} for #{command}")
        print_usage(@err)
        return 1
      end

      if @argv.first == "--help" || @argv.first == "-h"
        @argv.shift
        print_command_help(command, @out)
        return 0
      end

      case command
      when "lex"
        lex_command
      when "parse"
        parse_command
      when "format"
        format_command
      when "lint"
        lint_command
      when "check"
        check_command
      when "lower"
        lower_command
      when "emit-c"
        emit_c_command
      when "build"
        build_command
      when "test"
        test_command
      when "run"
        run_command
      when "run-module"
        app_command
      when "new"
        new_command
      when "debug"
        debug_command
      when "toolchain"
        toolchain_command
      when "deps"
        deps_command
      when "bindgen"
        bindgen_command
      when "cache"
        cache_command
      when "docs"
        docs_command
      when "snapshot"
        snapshot_command
      when "lsp"
        lsp_command
      when "dap"
        dap_command
      when "completions"
        completions_command
      else
        print_usage(@err)
        1
      end
    rescue StandardError => e
      raise unless known_cli_error?(e)

      @err.puts(ErrorFormatter.format(e, color: use_color?(@err)))
      1
    end

